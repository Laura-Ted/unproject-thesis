"""The three pictures the RQ3 argument is made of.

Drawn from the summary rather than from anything held aside, so a figure is
regenerated by rerunning the analysis and can never disagree with the table
beside it.

Every axis names its unit and, where it has one, its frame. A plot of metres
that does not say which metres is not a result.

Deterministic on purpose: SVG carries a timestamp and a random id salt by
default, and a figure whose bytes change on every run cannot be checked into a
thesis repository and trusted.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from unproject.rq3.analyse import Rq3Summary
from unproject.rq3.annotations import CONVENTION

if TYPE_CHECKING:
    from matplotlib.figure import Figure

POSITION_FIGURE = "rq3-position-error.svg"
VELOCITY_FIGURE = "rq3-axis-velocity.svg"
JITTER_FIGURE = "rq3-depth-jitter.svg"

# Fixed so two runs over the same summary produce the same bytes.
_HASH_SALT = "unproject-rq3"

_FRAME = f"{CONVENTION}: +X right, +Z forward"


def write_figures(summary: Rq3Summary, directory: Path) -> list[Path]:
    """Draw whatever the summary has the data for. Returns what was written.

    A figure with nothing to plot is skipped rather than drawn empty: an empty
    axis reads as a measurement of zero.
    """
    import matplotlib

    # Before pyplot is imported: the analysis writes files and never opens a
    # window, and the default backend would look for a display.
    matplotlib.use("Agg")
    matplotlib.rcParams["svg.hashsalt"] = _HASH_SALT

    directory.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, build in (
        (POSITION_FIGURE, _position_error),
        (VELOCITY_FIGURE, _axis_velocity),
        (JITTER_FIGURE, _depth_jitter),
    ):
        figure = build(summary)
        if figure is None:
            continue
        path = directory / name
        # Date stripped for the same reason as the salt.
        figure.savefig(path, format="svg", bbox_inches="tight", metadata={"Date": None})
        _close(figure)
        written.append(path)
    return written


def _position_error(summary: Rq3Summary) -> Figure | None:
    """Lateral against depth error, per marker, with the ruler drawn on it.

    The figure the argument rests on: if depth error towers over lateral error
    and over the marker uncertainty, that is the finding, visible at a glance.
    """
    import matplotlib.pyplot as plt

    rows = [row for row in summary.positions if row.samples > 0]
    if not rows:
        return None

    figure, axes = plt.subplots(figsize=(7.0, 4.0))
    positions = range(len(rows))
    width = 0.38
    axes.bar(
        [value - width / 2 for value in positions],
        [row.lateral_abs_median_metres or 0.0 for row in rows],
        width,
        label="lateral (X)",
        color="#4878a8",
    )
    axes.bar(
        [value + width / 2 for value in positions],
        [row.depth_abs_median_metres or 0.0 for row in rows],
        width,
        label="depth (Z)",
        color="#a84848",
    )
    # The measurement is only a measurement above this line.
    for index, row in zip(positions, rows, strict=True):
        # Labelled once, so the legend carries one entry rather than one a bar.
        axes.hlines(
            row.marker_uncertainty_metres,
            index - 0.5,
            index + 0.5,
            colors="#333333",
            linestyles="dotted",
            linewidth=1.0,
            label="marker uncertainty" if index == 0 else "_nolegend_",
        )

    axes.set_xticks(list(positions))
    axes.set_xticklabels([f"{row.marker}\n(n={row.samples})" for row in rows])
    axes.set_ylabel("absolute median error (metres)")
    axes.set_title(f"Position error by marker\n{_FRAME}", fontsize=10)
    axes.legend(fontsize=8)
    axes.spines[["top", "right"]].set_visible(False)
    return figure


def _axis_velocity(summary: Rq3Summary) -> Figure | None:
    """Apparent frame-to-frame velocity per axis, raw against smoothed.

    Both are drawn because the raw figure is the project's own result and the
    smoothed one is an interpretation of it.
    """
    import matplotlib.pyplot as plt

    rows = [effect for effect in summary.smoothing if effect.raw.steps > 0]
    if not rows:
        return None

    figure, axes = plt.subplots(figsize=(7.5, 4.0))
    positions = range(len(rows))
    width = 0.2
    series = (
        ("lateral raw", -1.5, "#4878a8", "raw", "lateral_median_metres_per_second"),
        ("lateral smoothed", -0.5, "#9dbcd8", "smoothed", "lateral_median_metres_per_second"),
        ("depth raw", 0.5, "#a84848", "raw", "depth_median_metres_per_second"),
        ("depth smoothed", 1.5, "#d8a0a0", "smoothed", "depth_median_metres_per_second"),
    )
    for label, offset, colour, which, field in series:
        values = [getattr(getattr(effect, which), field) or 0.0 for effect in rows]
        axes.bar(
            [value + offset * width for value in positions],
            values,
            width,
            label=label,
            color=colour,
        )

    axes.set_xticks(list(positions))
    axes.set_xticklabels([_wrap(effect.label) for effect in rows], fontsize=8)
    axes.set_ylabel("median apparent velocity (metres per second)")
    delays = [
        effect.response_delay_seconds
        for effect in rows
        if effect.response_delay_seconds is not None
    ]
    cost = f"; smoothing lags by up to {max(delays):.2f} s" if delays else ""
    axes.set_title(f"Apparent velocity by axis, raw and smoothed{cost}\n{_FRAME}", fontsize=10)
    axes.legend(fontsize=8)
    axes.spines[["top", "right"]].set_visible(False)
    return figure


def _depth_jitter(summary: Rq3Summary) -> Figure | None:
    """Depth jitter as a fraction of range, per interval.

    Plotted as a fraction rather than in metres because that is the form the
    error takes: a body at forty metres jumps by a metre, one at four does not.
    """
    import matplotlib.pyplot as plt

    rows = [
        motion
        for motion in [
            summary.overall_motion,
            *summary.stationary_motion,
            *summary.walking_motion,
        ]
        if motion.depth_jitter_fraction_of_range is not None
    ]
    if not rows:
        return None

    figure, axes = plt.subplots(figsize=(7.0, 4.0))
    positions = range(len(rows))
    axes.bar(
        list(positions),
        [100.0 * (motion.depth_jitter_fraction_of_range or 0.0) for motion in rows],
        0.6,
        color="#a84848",
    )
    axes.set_xticks(list(positions))
    axes.set_xticklabels([_wrap(motion.label) for motion in rows], fontsize=8)
    axes.set_ylabel("median frame-to-frame depth step (% of range)")
    axes.set_title(f"Depth jitter against distance\n{_FRAME}", fontsize=10)
    axes.spines[["top", "right"]].set_visible(False)
    return figure


def _wrap(label: str, width: int = 14) -> str:
    """Break a label so a tick does not run into its neighbour."""
    words = label.split()
    lines: list[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) > width and current:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return "\n".join(lines)


def _close(figure: Figure) -> None:
    import matplotlib.pyplot as plt

    plt.close(figure)
